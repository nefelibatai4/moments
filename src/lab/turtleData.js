// bottom 是旧字段，保留成 solution 的别名，免得别处的旧代码突然读空。
export const TURTLE_SOUPS = TURTLE_CASES.map((soup) => ({ ...soup, bottom: soup.solution }))

export const TURTLE_BY_ID = Object.fromEntries(TURTLE_SOUPS.map((soup) => [soup.id, soup]))

export function pickTurtle(excludeId = '') {
  const pool = TURTLE_SOUPS.filter((soup) => soup.id !== excludeId)
  const list = pool.length > 0 ? pool : TURTLE_SOUPS
  return list[Math.floor(Math.random() * list.length)]
}

// ── Ace 的纯函数 ───────────────────────────────────────────────────
// 两个函数都不读 DOM / localStorage / 时间，也不修改传入的题目：
// 同样的输入永远得到同样的输出，方便在任意主持端重放和测试。
const ACE_VERDICTS = new Set(['yes', 'no', 'irrelevant', 'partial'])

function normalizeForAce(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '')
}

function clueTokens(clue, field) {
  const list = Array.isArray(clue?.[field]) ? clue[field] : []
  return [...new Set(
    list
      .map((token) => normalizeForAce(token))
      .filter((token) => token.length > 0),
  )]
}

/**
 * 离线核对用：按关键词回答一条提问（线上 UI 已不再调用，真判定走 DeepSeek）。
 *
 * 对每个 clue，累加命中 ask 关键词的字数（越具体的关键词权重越高），
 * 取分数最高的一条线索给出的 verdict。完全没命中就答「无关」。
 *
 * @param {string} question 玩家的问题
 * @param {object} soup TURTLE_SOUPS 里的一项
 * @returns {'yes'|'no'|'irrelevant'|'partial'}
 */
export function aceAnswer(question, soup) {
  const text = normalizeForAce(question)
  if (!text || !soup || !Array.isArray(soup.clues)) return 'irrelevant'

  let bestScore = 0
  let bestVerdict = 'irrelevant'

  for (const clue of soup.clues) {
    if (!ACE_VERDICTS.has(clue?.verdict)) continue
    let score = 0
    for (const token of clueTokens(clue, 'ask')) {
      if (text.includes(token)) score += token.length
    }
    // 同分时先出现的线索优先；数据里把肯定线索排在前面，避免被
    // 兜底否定词抢走。完全没有命中时保持「无关」。
    if (score > bestScore) {
      bestScore = score
      bestVerdict = clue.verdict
    }
  }

  return bestVerdict
}

/**
 * 离线核对用：按关键词判定一条猜底（线上 UI 已不再调用）。
 *
 * 只统计肯定线索里的 judge 关键词：至少命中两个不同的关键词才算猜中。
 * 这样可以挡掉只碰到一个宽泛名词的猜测，也不需要理解整段语义。
 *
 * @param {string} guess 玩家写下的完整猜测
 * @param {object} soup TURTLE_SOUPS 里的一项
 * @returns {boolean}
 */
export function aceJudge(guess, soup) {
  const text = normalizeForAce(guess)
  if (text.length < 4 || !soup || !Array.isArray(soup.clues)) return false

  const matched = new Set()
  for (const clue of soup.clues) {
    if (clue?.verdict !== 'yes') continue
    for (const token of clueTokens(clue, 'judge')) {
      if (text.includes(token)) matched.add(token)
    }
  }
  return matched.size >= 2
}
